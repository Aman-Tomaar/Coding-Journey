import numpy as np

array1 = np.array([1, 2, 3, 4])  # Create a NumPy array
print(array1 * 2)  # Output: [2 4 6 8] - NumPy performs element-wise multiplication

array2 = [1, 2, 3, 4]  # Create a Python list
print(
    array2 * 2
)  # Output: [1, 2, 3, 4, 1, 2, 3, 4] - Python list multiplication repeats the list
